  AI.ATIN_CD_ATO_INSEGURO CODGIO_ATO_INSEGURO,
  (SELECT DISTINCT  TT.TETR_TX_TEXTO_TRADUZIDO FROM TEXTO_TRADUZIDO TT, TEXTO T WHERE T.TEXT_CD_TEXTO = TT.TEXT_CD_TEXTO AND T.TEXT_CD_TEXTO = AI.TEXT_CD_TEXTO) ATO_INSEGURO,
