  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Regra de Ouro' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
