     AND L.TEXT_CD_TEXTO = T.TEXT_CD_TEXTO
     AND L.LOCA_CD_LOCAL = AC.LOCA_CD_LOCAL
   GROUP BY L.LOCA_CD_LOCAL
   ) AS LOCAL_ACIDENTE,
  E.ESTA_NM_NOME ESTADO,
  TA.TIPA_CD_TIPOLOGIA_ACIDENTE CODIGO_TIPOLOGIA_ACIDENTE,
  TT.TETR_TX_TEXTO_TRADUZIDO TIPLOGIA_ACIDENTE,
