   --LOCAL DO ACIDENTE
  LOCA.LOCA_CD_LOCAL CODIGO_LOCAL,
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Local do Acidente' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
   	FROM LOCAL L,
   	     TEXTO T,
   	     TEXTO_TRADUZIDO TT
   WHERE TT.TEXT_CD_TEXTO = T.TEXT_CD_TEXTO
     AND L.TEXT_CD_TEXTO = T.TEXT_CD_TEXTO
     AND L.LOCA_CD_LOCAL = AC.LOCA_CD_LOCAL
   GROUP BY L.LOCA_CD_LOCAL
   ) AS LOCAL_ACIDENTE,
  E.ESTA_NM_NOME ESTADO,
  TA.TIPA_CD_TIPOLOGIA_ACIDENTE CODIGO_TIPOLOGIA_ACIDENTE,
  TT.TETR_TX_TEXTO_TRADUZIDO TIPLOGIA_ACIDENTE,
  -- TIPO AIDENTE DE TRÂNSITO
   (
    SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Tipo Acidente de Trânsito' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
