  AC.ACID_DT_INCLUSAO DATA_CRIACAO,
  AC.ACID_CD_CHAVE_ALTERACAO ALTERADO_POR,
  AC.ACID_DT_ALTERACAO DATA_ALTERACAO,
  -- ARQUIVOS ANXADOS
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Arquivos Anexados' VALUE ANEXO.ACAN_NM_ARQUIVO
       )
       returning CLOB
    )      	
   	FROM ACIDENTE_ANEXO ANEXO
   WHERE ANEXO.ACID_CD_ACIDENTE = AC.ACID_CD_ACIDENTE   
   GROUP BY ANEXO.ACID_CD_ACIDENTE
   ) AS ARQUIVOS
