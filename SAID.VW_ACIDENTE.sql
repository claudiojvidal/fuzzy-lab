  LOCA.LOCA_CD_LOCAL CODIGO_LOCAL,
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Local do Acidente' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
