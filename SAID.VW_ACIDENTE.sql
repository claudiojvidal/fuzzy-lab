   GROUP BY ARO.ACID_CD_ACIDENTE
   ) AS REGRA_OURO,  
  -- DENOMINAÇÃO DO ACIDNTE
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Denominação do Acidente' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
   	FROM DENOMINACAO D,
   	     ACIDENTE_DENOMINACAO AD,
   	     TEXTO T,
   	     TEXTO_TRADUZIDO TT
   WHERE AD.DENO_CD_DENOMINACAO = D.DENO_CD_DENOMINACAO
     AND AC.ACID_CD_ACIDENTE = AD.ACID_CD_ACIDENTE
     AND T.TEXT_CD_TEXTO = TT.TEXT_CD_TEXTO
     AND D.TEXT_CD_TEXTO = T.TEXT_CD_TEXTO
   GROUP BY AD.ACID_CD_ACIDENTE
   ) AS DENOMICAO_ACIDENTE,
  -- SUB-DENOMINAÇÃO DO ACIDNTE
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Denominação do Acidente' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
   	FROM DENOMINACAO D,
   	     ACIDENTE_DENOMINACAO AD,
   	     TEXTO T,
   	     TEXTO_TRADUZIDO TT
