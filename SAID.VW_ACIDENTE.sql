SELECT * FROM (
SELECT 
  AC.ACID_CD_ACIDENTE CODIGO,
  (SELECT ORGA_NM_ORGAO FROM ORGAO WHERE ORGA_SQ_ORGAO = FN_OBTEM_ORGAO_SUPERIOR(AC.ORGA_SQ_ORGAO,8)) NIVEL_1,
  (SELECT ORGA_NM_ORGAO FROM ORGAO WHERE ORGA_SQ_ORGAO = FN_OBTEM_ORGAO_SUPERIOR(Ac.ORGA_SQ_ORGAO,5)) NIVEL_2,
  (SELECT ORGA_NM_ORGAO FROM ORGAO WHERE ORGA_SQ_ORGAO = FN_OBTEM_ORGAO_SUPERIOR(AC.ORGA_SQ_ORGAO,6)) NIVEL_3,
  NULL NIVEL_4,
  O.ORGA_DT_VERSAO_INICIAL VIGENCIA_INICIAL,
  O.ORGA_DT_VERSAO_FINAL VIGENCIA_FINAL,
  AC.ACID_TX_DESCRICAO DESCRICAO,
  AC.ACID_NM_ACIDENTE EVENTO,
  AC.ACID_DT_ACIDENTE DATA_ACIDENTE,
  AC.ACID_HR_ACIDENTE HORA_ACIDENTE,
  (SELECT COUNT(*) FROM ACIDENTADO ACC WHERE ACC.ACID_CD_ACIDENTE = AC.ACID_CD_ACIDENTE) QTDE_ACIDENTADOS,
  -- ACIDENTADO
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Código Acidentado' VALUE ACDT.ACDO_CD_ACIDENTADO,
       	  'Nome Acidentado' VALUE   ACDT.ACDO_NM_ACIDENTADO,
       	  'Tipo de Força de Trabalho' VALUE TFT.TIFT_NM_FORCA,
       	  'Tipo de Lesão' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
   	FROM ACIDENTADO ACDT
   		 LEFT JOIN TIPO_LESAO TL ON (TL.TILE_CD_TIPO_LESAO = ACDT.TILE_CD_TIPO_LESAO)
   		 LEFT JOIN TEXTO T ON (T.TEXT_CD_TEXTO = TL.TEXT_CD_TEXTO)
   		 LEFT JOIN TEXTO_TRADUZIDO TT ON (TT.TEXT_CD_TEXTO = T.TEXT_CD_TEXTO),
   	     TIPO_FORCA_TRABALHO TFT
   WHERE ACDT.ACID_CD_ACIDENTE = AC.ACID_CD_ACIDENTE
     AND TFT.TIFT_CD_FORCA = ACDT.TIFT_CD_FORCA
   GROUP BY ACDT.ACID_CD_ACIDENTE
   ) AS ACIDENTADO,
  AC.ACID_VL_ESTIMATIVA_CUSTO ESTIMATIVA_CUSTO,
  -- ORGÃO E SUAS VIGÊNCIAS
  -- TIPO DE OCORRÊNCIA
  TOC.TIOC_CD_TIPO_OCORRENCIA CODIGO_TIPO_OCORRENCIA,
  (SELECT DISTINCT TT.TETR_TX_TEXTO_TRADUZIDO FROM TEXTO_TRADUZIDO TT, TEXTO T WHERE T.TEXT_CD_TEXTO = TT.TEXT_CD_TEXTO AND T.TEXT_CD_TEXTO = TOC.TEXT_CD_TEXTO) TPO_OCORRRENCIA,
  -- CAUSA IMEDIATA
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT	
       (	
       	  'Causa Imediata' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
   	FROM CAUSA_IMEDIATA CI,
   		 ACIDENTE_CAUSA_IMEDIATA ACI,
   	     TEXTO T,
   	     TEXTO_TRADUZIDO TT
   WHERE TT.TEXT_CD_TEXTO = T.TEXT_CD_TEXTO
     AND CI.TEXT_CD_TEXTO = T.TEXT_CD_TEXTO
     AND ACI.ACID_CD_ACIDENTE = AC.ACID_CD_ACIDENTE
     AND ACI.CAIM_CD_CAUSA_IMEDIATA = CI.CAIM_CD_CAUSA_IMEDIATA
   GROUP BY ACI.ACID_CD_ACIDENTE
   ) AS CAUSA_IMEDIATA,
  -- CAUSA BÁSICA
  (
  	SELECT 
  	JSON_ARRAYAGG  	
    (  		
       JSON_OBJECT
       		
       (	
       	  'Causa Básica' VALUE TT.TETR_TX_TEXTO_TRADUZIDO
       )
       returning CLOB
    )      	
   	FROM CAUSA_BASICA CB,
   		 ACIDENTE_CAUSA_BASICA ACB,
   	     TEXTO T,
   	     TEXTO_TRADUZIDO TT
