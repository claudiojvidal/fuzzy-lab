  IM.IMOV_CD_IMOVEL CODIGO_IMOVEL,
  IM.IMOV_NM_IMOVEL NOME_IMOVEL,
  P.PAIS_CD_CODIGO CODIGOPAS,
  P.PAIS_NM_PAIS PAIS,
  AC.ACID_TX_ACAO_IMEDIATA ACAO_IMEDIATA,
  AC.ACID_TX_ACAO_CORRETIVA ACAO_CORRETIVA,
